import { readdirSync, writeFileSync, mkdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = join(__dirname, '..')
const LIB_DIR = join(ROOT, 'library')
const OUT_DIR = join(ROOT, 'src/ui/library')
const OUT = join(OUT_DIR, 'index.ts')

const files = readdirSync(LIB_DIR)
  .filter(f => f.endsWith('.json') && !f.startsWith('_'))
  .sort()

const imports = files.map((f, i) => `import e${i} from '../../../library/${f}'`).join('\n')
const list = files.map((_, i) => `e${i}`).join(', ')

const out = `// AUTOGENERATED by scripts/generate-library-index.mjs — do not edit.
import type { LibraryEntry } from './types'
${imports}

export const libraryEntries: LibraryEntry[] = [${list}]
`

mkdirSync(OUT_DIR, { recursive: true })
writeFileSync(OUT, out)
console.log(`Generated ${OUT} with ${files.length} entries`)
